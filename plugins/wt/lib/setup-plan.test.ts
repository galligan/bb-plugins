import assert from "node:assert/strict";
import { test } from "node:test";

import {
  resolveSetupPlan,
  effectiveScripts,
  type SetupPlan,
} from "./setup-plan.ts";

const codexToml = `# THIS IS AUTOGENERATED. DO NOT EDIT MANUALLY
version = 1
name = "skillset"

[setup]
script = "./scripts/bootstrap.sh codex"

[cleanup]
script = "./scripts/bootstrap.sh teardown"
`;

test("a bb hook file wins, because bb core runs it itself", () => {
  assert.deepEqual(
    resolveSetupPlan({ hasBbHook: true, codexEnvironmentToml: codexToml }),
    { source: "bb-hook" },
  );
});

test("falls back to the Codex environment scripts", () => {
  assert.deepEqual(
    resolveSetupPlan({ hasBbHook: false, codexEnvironmentToml: codexToml }),
    {
      source: "codex",
      setup: "./scripts/bootstrap.sh codex",
      cleanup: "./scripts/bootstrap.sh teardown",
    },
  );
});

test("a Codex file with only setup has no cleanup", () => {
  assert.deepEqual(
    resolveSetupPlan({
      hasBbHook: false,
      codexEnvironmentToml: '[setup]\nscript = "bun install"\n',
    }),
    { source: "codex", setup: "bun install", cleanup: null },
  );
});

test("no recognised config means a bare worktree", () => {
  assert.deepEqual(
    resolveSetupPlan({ hasBbHook: false, codexEnvironmentToml: null }),
    { source: "none" },
  );
  assert.deepEqual(
    resolveSetupPlan({
      hasBbHook: false,
      codexEnvironmentToml: 'version = 1\nname = "x"\n',
    }),
    { source: "none" },
  );
});

test("unparseable Codex config fails loudly", () => {
  assert.throws(
    () =>
      resolveSetupPlan({ hasBbHook: false, codexEnvironmentToml: "[setup\n" }),
    /\.codex\/environments\/environment\.toml/u,
  );
});

test("effective scripts apply each step mode independently and always defer to bb hooks", () => {
  const modes = ["detected", "custom", "off"] satisfies (
    "detected" | "custom" | "off"
  )[];
  const cases: {
    plan: SetupPlan;
    detected: { setup: string | null; cleanup: string | null };
  }[] = [
    { plan: { source: "bb-hook" }, detected: { setup: null, cleanup: null } },
    {
      plan: { source: "codex", setup: "repo setup", cleanup: "repo cleanup" },
      detected: { setup: "repo setup", cleanup: "repo cleanup" },
    },
    {
      plan: { source: "codex", setup: "repo setup", cleanup: null },
      detected: { setup: "repo setup", cleanup: null },
    },
    {
      plan: { source: "codex", setup: null, cleanup: "repo cleanup" },
      detected: { setup: null, cleanup: "repo cleanup" },
    },
    { plan: { source: "none" }, detected: { setup: null, cleanup: null } },
  ];
  for (const { plan, detected } of cases) {
    for (const setupMode of modes)
      for (const cleanupMode of modes) {
        const result = effectiveScripts(plan, {
          setup: { mode: setupMode, script: "custom setup" },
          cleanup: { mode: cleanupMode, script: "custom cleanup" },
        });
        if (plan.source === "bb-hook") {
          assert.deepEqual(result, { source: "bb-hook" });
          continue;
        }
        assert.equal(result.source, "plugin");
        if (result.source !== "plugin") continue;
        const setup = {
          detected: detected.setup,
          custom: "custom setup",
          off: null,
        };
        const cleanup = {
          detected: detected.cleanup,
          custom: "custom cleanup",
          off: null,
        };
        assert.equal(result.setup, setup[setupMode]);
        assert.equal(result.cleanup, cleanup[cleanupMode]);
        assert.equal(
          result.origin.setup,
          setupMode === "detected"
            ? detected.setup === null
              ? "none"
              : "codex"
            : setupMode,
        );
        assert.equal(
          result.origin.cleanup,
          cleanupMode === "detected"
            ? detected.cleanup === null
              ? "none"
              : "codex"
            : cleanupMode,
        );
      }
    assert.deepEqual(
      effectiveScripts(plan, null),
      plan.source === "bb-hook"
        ? plan
        : {
            source: "plugin",
            ...detected,
            origin: {
              setup: detected.setup === null ? "none" : "codex",
              cleanup: detected.cleanup === null ? "none" : "codex",
            },
          },
    );
  }
});
